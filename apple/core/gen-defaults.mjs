// Generates defaults.gen.js: openGym's default profile (`DEF` in store/useStore.js), copied
// verbatim. The store itself cannot run headless (it is wired to React, sync and
// localStorage), so its DEF literal is lifted out and evaluated with the two constants it
// spreads in. A new setting upstream reaches the native app with the next build.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { WC_DEFAULT } from '../../frontend/src/lib/workout-controls.js'
import { DEFAULT_TEMPLATE_ID } from '../../frontend/src/lib/structuralBalanceTemplates.js'

const here = p => fileURLToPath(new URL(p, import.meta.url))

export function readDefaults() {
  const src = readFileSync(here('../../frontend/src/store/useStore.js'), 'utf8')
  const start = src.indexOf('export const DEF = {')
  const end = src.indexOf('\n}\n', start)
  if (start < 0 || end < 0) throw new Error('DEF not found in store/useStore.js')
  const literal = src.slice(start + 'export const DEF = '.length, end + 2)
  return new Function('WC_DEFAULT', 'DEFAULT_TEMPLATE_ID', `return (${literal})`)(WC_DEFAULT, DEFAULT_TEMPLATE_ID)
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = '// Generated by gen-defaults.mjs from frontend/src/store/useStore.js. Do not edit.\n' +
    `export const DEF = ${JSON.stringify(readDefaults(), null, 2)}\n`
  writeFileSync(here('./defaults.gen.js'), out)
  console.log('defaults.gen.js written')
}
